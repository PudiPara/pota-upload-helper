#!/usr/bin/env python3
"""Rebuild locations.py: pota.app's location codes (US-ND, JP-TK, ...) -> their names.

    python3 scripts/update_locations.py

pota.app's park record lists a park's location codes sorted by code and their names sorted by name,
so the two lists can't be paired by position (US-4239: US-ND is North Dakota, not New York). The app
looks names up in this table instead; it is shipped with the app, so users' copies never ask
pota.app for it. Run this by hand now and then and commit the result.
"""
import datetime as dt
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
req = urllib.request.Request("https://api.pota.app/locations", headers={"User-Agent": "potaroo-dev/locations"})
with urllib.request.urlopen(req, timeout=60) as r:
    data = json.loads(r.read().decode("utf-8"))
names = {x["locationDesc"]: x["locationName"] for x in data if x.get("locationDesc") and x.get("locationName")}
if len(names) < 1000:
    sys.exit("only %d locations - not writing" % len(names))
lines = ['"""pota.app location code -> name (%d, from api.pota.app/locations on %s).' % (len(names), dt.date.today()),
         "Generated by scripts/update_locations.py - do not edit by hand.\"\"\"", "", "NAMES = {"]
lines += ["    %s: %s," % (json.dumps(k), json.dumps(v, ensure_ascii=False)) for k, v in sorted(names.items())]
lines += ["}", ""]
with open(os.path.join(ROOT, "locations.py"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))
print("locations.py: %d locations" % len(names))
