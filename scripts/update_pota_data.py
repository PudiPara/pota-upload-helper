#!/usr/bin/env python3
"""Rebuild the pota.app data shipped with the app (run by hand before a release, then commit):

    python3 scripts/update_pota_data.py                      (downloads both)
    python3 scripts/update_pota_data.py all_parks_ext.csv    (parks from a copy already downloaded)

  assets/parks.tsv.gz   every park: reference, name, location codes, grid, latitude, longitude, active
                        (1/0 - a park pota.app retired stays, so a record of it keeps its name and place)
                        (from https://pota.app/all_parks_ext.csv, the list loggers like QLog use)
  assets/pota-data.txt  the data version (YYYY.MM.DD, UTC) - written only when the data changed
  locations.py          location code -> name (from api.pota.app/locations); pota.app's park record
                        sorts codes and names apart, so they can't be paired by position

Shipped, so users' copies don't download these; a park newer than the table is still looked up
on pota.app by spots.park_info.
"""
import csv
import datetime as dt
import gzip
import io
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = {"User-Agent": "potaroo-dev/update_pota_data"}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120) as r:
        return r.read().decode("utf-8")


def write(rel, data):
    """Write a generated file; -> True when its bytes changed."""
    path = os.path.join(ROOT, *rel.split("/"))
    try:
        with open(path, "rb") as fh:
            if fh.read() == data:
                return False
    except OSError:
        pass
    with open(path, "wb") as fh:
        fh.write(data)
    return True


def parks(path=None):
    if path:
        with open(path, encoding="utf-8-sig") as fh:
            text = fh.read()
    else:
        text = get("https://pota.app/all_parks_ext.csv")
    rows = [r for r in csv.DictReader(io.StringIO(text)) if r.get("reference")]
    active = sum(1 for r in rows if r.get("active") == "1")
    if active < 50000:
        sys.exit("only %d active parks - not writing" % active)
    clean = lambda s: (s or "").replace("\t", " ").replace("\n", " ").strip()
    cols = ("reference", "name", "locationDesc", "grid", "latitude", "longitude", "active")
    body = "\n".join("\t".join(clean(r[k]) for k in cols) for r in rows) + "\n"
    changed = write("assets/parks.tsv.gz", gzip.compress(body.encode("utf-8"), 9, mtime=0))   # mtime=0: same parks, same bytes
    print("assets/parks.tsv.gz: %d parks (%d active)%s" % (len(rows), active, "" if changed else ", no change"))
    return changed


def locations():
    names = {x["locationDesc"]: x["locationName"] for x in json.loads(get("https://api.pota.app/locations"))
             if x.get("locationDesc") and x.get("locationName")}
    if len(names) < 1000:
        sys.exit("only %d locations - not writing" % len(names))
    lines = ['"""pota.app location code -> name (%d, from api.pota.app/locations).' % len(names),
             "Generated by scripts/update_pota_data.py - do not edit by hand.\"\"\"", "", "NAMES = {"]
    lines += ["    %s: %s," % (json.dumps(k), json.dumps(v, ensure_ascii=False)) for k, v in sorted(names.items())]
    changed = write("locations.py", "\n".join(lines + ["}", ""]).encode("utf-8"))
    print("locations.py: %d locations%s" % (len(names), "" if changed else ", no change"))
    return changed


if __name__ == "__main__":
    changed = parks(sys.argv[1]) if len(sys.argv) > 1 else parks() | locations()
    if changed:   # a new data version: the app and the updater compare it (potacommon.data_version)
        v = dt.datetime.now(dt.timezone.utc).strftime("%Y.%m.%d")
        write("assets/pota-data.txt", (v + "\n").encode())
        print("assets/pota-data.txt:", v)
